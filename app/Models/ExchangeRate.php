<?php

namespace App\Models;

use App\Casts\AsBigDecimal;
use App\Enums\ExchangeRateOrigin;
use Brick\Math\BigDecimal;
use Database\Factories\ExchangeRateFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Builder;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;
use Illuminate\Support\Carbon;

/**
 * The exchange rate of one day, Bs per USD (COT-030, design Decision 11). Rows are append-only: the
 * only write to an existing row is the supersede of `RecordManualExchangeRate`, which sets
 * `superseded_at` and `superseded_by_id`. A day has at most one effective row (`effective_date`,
 * generated by the database).
 *
 * @property int $id
 * @property Carbon $rate_date
 * @property BigDecimal $value
 * @property ExchangeRateOrigin $origin
 * @property Carbon|null $source_updated_at
 * @property int|null $recorded_by
 * @property Carbon|null $superseded_at
 * @property int|null $superseded_by_id
 * @property Carbon|null $created_at
 * @property-read User|null $recordedBy
 */
#[Fillable(['rate_date', 'value', 'origin', 'source_updated_at', 'recorded_by', 'superseded_at', 'superseded_by_id'])]
class ExchangeRate extends Model
{
    /** @use HasFactory<ExchangeRateFactory> */
    use HasFactory;

    public const UPDATED_AT = null;

    /** The largest rate `value` DECIMAL(14,4) stores; a larger one is not a usable rate. */
    public const MAX_VALUE = '9999999999.9999';

    /**
     * @return array<string, string>
     */
    protected function casts(): array
    {
        return [
            'rate_date' => 'date',
            'value' => AsBigDecimal::class.':4',
            'origin' => ExchangeRateOrigin::class,
            'source_updated_at' => 'datetime',
            'recorded_by' => 'integer',
            'superseded_at' => 'datetime',
            'superseded_by_id' => 'integer',
        ];
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function recordedBy(): BelongsTo
    {
        return $this->belongsTo(User::class, 'recorded_by');
    }

    public function isEffective(): bool
    {
        return $this->superseded_at === null;
    }

    /**
     * The rate history (spec §8): every row, effective and superseded, newest first.
     *
     * @param  Builder<self>  $query
     */
    public function scopeHistory(Builder $query): void
    {
        $query->with('recordedBy:id,first_name,last_name')->orderByDesc('rate_date')->orderByDesc('id');
    }
}
